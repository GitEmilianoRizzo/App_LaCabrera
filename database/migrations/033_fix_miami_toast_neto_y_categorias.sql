-- Control: venta neta por local y mes (debe ser igual al Net sales del Sales Summary de Toast)
SELECT f.Codigo, FORMAT(v.FechaNegocio, 'yyyy-MM') AS Mes, COUNT(*) AS Tickets,
       SUM(v.ImporteNeto) AS NetSales,
       SUM(COALESCE(v.ImporteNetoSinImpuesto, v.ImporteNeto) - ISNULL(v.ImporteServicio, 0)) AS VentaNetaDashboard
FROM fact.VentaTicket v
JOIN dim.Franquicia f ON f.FranquiciaId = v.FranquiciaId
JOIN @Miami m ON m.FranquiciaId = v.FranquiciaId
WHERE v.EstaAnulado = 0 AND v.FechaNegocio >= '2026-08-01'
GROUP BY f.Codigo, FORMAT(v.FechaNegocio, 'yyyy-MM')
ORDER BY f.Codigo, Mes;
