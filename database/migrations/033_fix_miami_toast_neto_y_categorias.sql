UPDATE p
SET TipoPlatoId = tp.TipoPlatoId,
    FechaModificacion = SYSDATETIME(),
    UsuarioModificacion = 'MIGRACION_033'
FROM dim.Producto p
JOIN @Miami m ON m.FranquiciaId = p.FranquiciaId
JOIN @Categorias c ON c.HashNombre = CONVERT(BINARY(8), HASHBYTES('SHA2_256', p.Nombre))
JOIN dim.TipoPlato tp ON tp.Codigo = c.CodigoTipoPlato
WHERE ISNULL(p.TipoPlatoId, 0) <> tp.TipoPlatoId;

PRINT 'Productos de Miami recategorizados: ' + CAST(@@ROWCOUNT AS VARCHAR);

