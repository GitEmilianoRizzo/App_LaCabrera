    CategoriaProducto = tp.Codigo,
    FechaModificacion = SYSDATETIME(),
    UsuarioModificacion = 'MIGRACION_033'
FROM fact.VentaTicketDetalle d
JOIN @Miami m ON m.FranquiciaId = d.FranquiciaId
JOIN dim.Producto p ON p.ProductoId = d.ProductoId
JOIN dim.TipoPlato tp ON tp.TipoPlatoId = p.TipoPlatoId
WHERE ISNULL(d.TipoPlatoId, 0) <> p.TipoPlatoId
   OR ISNULL(d.CategoriaProducto, '') <> tp.Codigo;

