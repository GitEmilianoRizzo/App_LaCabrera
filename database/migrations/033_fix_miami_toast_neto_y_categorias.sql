-- =====================================================
-- Miami (Toast): venta neta = "Net sales" de Toast y categorías de producto parejas entre meses
--
-- 1) Venta neta. La plataforma calcula la venta neta como
--        COALESCE(ImporteNetoSinImpuesto, ImporteNeto) - ImporteServicio
--    y para Toast ImporteNeto ya es el "Net sales" del Sales Summary (sin impuestos ni servicio).
--    - Parser HTML anterior (hasta septiembre): ImporteNetoSinImpuesto venía como "total - impuesto",
--      que da algo menos que neto + servicio en cada ticket (Sunny 09/2026: -4.383 USD).
--    - Parser combinado (octubre): ImporteNetoSinImpuesto = neto, sin el servicio, que después se
--      volvía a restar (Sunny 10/2026: -50.552 USD).
--    Se deja ImporteNetoSinImpuesto = ImporteNeto + ImporteServicio en todos los tickets de Miami, así la
--    venta neta del Dashboard, Alertas e Informe es exactamente el Net sales cargado. El parser combinado
--    corregido manda ese mismo valor (net_amount_excl_tax).
--
-- 2) Categorías. Cada parser clasificaba distinto ("Entraña / Outside Skirt" quedaba como Guarnición por
--    la palabra "side", Filet Mignon/Dry Aged/vinos/cócteles como Otros). Se recategorizan los productos
--    con la regla única de services/parser-service/parsers/toast_categorias.py. La lista es el resultado
--    de aplicar esa regla a los productos de Miami, identificados por hash del nombre (no se guardan
--    nombres acá) y solo los que cambian.
--
-- Re-ejecutable: solo toca lo que todavía no está corregido.
-- =====================================================

SET NOCOUNT ON;

BEGIN TRANSACTION;

DECLARE @Miami TABLE (FranquiciaId INT PRIMARY KEY);
INSERT INTO @Miami SELECT FranquiciaId FROM dim.Franquicia WHERE Codigo IN ('MIAMI_SUNNY', 'MIAMI_COCONUT', 'MIAMI_MIDTOWN');

-- 1) Venta neta
UPDATE v
SET ImporteNetoSinImpuesto = v.ImporteNeto + ISNULL(v.ImporteServicio, 0),
    FechaModificacion = SYSDATETIME(),
    UsuarioModificacion = 'MIGRACION_033'
FROM fact.VentaTicket v
JOIN @Miami m ON m.FranquiciaId = v.FranquiciaId
WHERE v.ImporteNetoSinImpuesto IS NULL
   OR v.ImporteNetoSinImpuesto <> v.ImporteNeto + ISNULL(v.ImporteServicio, 0);

PRINT 'Tickets de Miami con la venta neta corregida: ' + CAST(@@ROWCOUNT AS VARCHAR);

